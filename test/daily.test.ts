import { describe, expect, it } from 'vitest'
import { поводыДляТревоги } from '../src/health/daily.js'

const всёХорошо = {
  каналыВсего: 3,
  каналыВСети: 3,
  отвалились: [],
  входящих: 12,
  исходящих: 20,
  неУшло: 0,
  зависших: 0,
  вОчереди: 0,
  чатыAmo: true,
}

describe('о чём сводка должна предупредить', () => {
  it('когда всё в порядке — молчит', () => {
    expect(поводыДляТревоги(всёХорошо)).toEqual([])
  })

  it('замечает сообщения, зависшие в пути', () => {
    // Ради этого всё и затевалось: 22 сентября WhatsApp перестал
    // доставлять, ошибок не было ни одной, и два дня никто не видел.
    const поводы = поводыДляТревоги({ ...всёХорошо, зависших: 5 })
    expect(поводы.join(' ')).toContain('висят в пути')
  })

  it('замечает отвалившийся номер и называет его', () => {
    expect(поводыДляТревоги({ ...всёХорошо, отвалились: ['WA PS'] }).join(' ')).toContain('WA PS')
  })

  it('замечает потерянные сообщения и неразобранную очередь', () => {
    expect(поводыДляТревоги({ ...всёХорошо, неУшло: 2 })).toHaveLength(1)
    expect(поводыДляТревоги({ ...всёХорошо, вОчереди: 50 })).toHaveLength(1)
    // Небольшая очередь — это нормальная работа, а не повод будить человека.
    expect(поводыДляТревоги({ ...всёХорошо, вОчереди: 5 })).toEqual([])
  })

  it('замечает потерю связи с amoCRM', () => {
    expect(поводыДляТревоги({ ...всёХорошо, чатыAmo: false }).join(' ')).toContain('amoCRM')
  })
})
